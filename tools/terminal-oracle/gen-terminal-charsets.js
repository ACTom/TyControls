// Writes source/tyControls.Terminal.Charsets.inc: xterm.js 6.0.0's G0-G3 character
// set tables (src/common/data/Charsets.ts CHARSETS), dumped from the built module --
// not copied by hand -- so the designations the core registers and the tables
// behind them cannot drift apart (plan, question 21). Upstream path and pin:
// lib-dump.js.
//
//   node tools/terminal-oracle/gen-terminal-charsets.js
//
// The keys are listed in for...in order, which is the order InputHandler registers
// its ESC ( ) * + - . / handlers in (InputHandler.ts:354-362): integer-like keys
// first, ascending, then the others as inserted. Tables are numbered by object
// identity in first-seen order from 1, so the aliases C/5, E/6, H/7 share one
// number; 'B' is undefined upstream (US ASCII, no replacement) and gets 0.
//
// The generated header carries the upstream version, the full commit and its date,
// never the time of the run or a path of this machine.
'use strict';
const path = require('path');
const L = require('./lib-dump.js');

const up = L.loadUpstream();
const { CHARSETS } = require(path.join(L.XTERM, L.OUT_DIR, 'common/data/Charsets.js'));

const keys = [];
for (const k in CHARSETS) keys.push(k);
const tables = [];
const ofKey = keys.map(k => {
  if (k.length !== 1) throw new Error('charset key is not one character: ' + k);
  const t = CHARSETS[k];
  if (t === undefined) return 0;
  let n = tables.indexOf(t);
  if (n < 0) { tables.push(t); n = tables.length - 1; }
  return n + 1;
});
for (const t of tables) {
  for (const [from, to] of Object.entries(t)) {
    if (from.length !== 1 || from.charCodeAt(0) < 0x20 || from.charCodeAt(0) > 0x7e) throw new Error('table key outside 0x20..0x7e: ' + JSON.stringify(from));
    const c = to.charCodeAt(0);
    // print() takes the first UTF-16 unit only (InputHandler.ts:552-557) -- the Dutch
    // table's "ij" prints as i -- so that unit is what is dumped; it must not be half
    // of a surrogate pair.
    if (c >= 0xD800 && c <= 0xDFFF) throw new Error('replacement outside the BMP: ' + JSON.stringify(to));
  }
}

const i = up.info;
const header = [
  'GENERATED by tools/terminal-oracle/gen-terminal-charsets.js -- do NOT edit by hand;',
  'change the script and rerun it. Upstream: xterm.js ' + i.version + ', commit ' + i.commit,
  `(${i.commitDate}), src/common/data/Charsets.ts CHARSETS.`,
  '',
  'TyTermCharsetKeys: the designation characters in for...in order (the order the',
  'core registers its ESC handlers in). TyTermCharsetOfKey: the table of each key,',
  '0 = none (US ASCII). TyTermCharsetMap[t, c]: what character c prints as under',
  'table t, 0 = unchanged.',
  '',
  'Derived from xterm.js, MIT:',
  '  Copyright (c) 2017-2019, The xterm.js authors (https://github.com/xtermjs/xterm.js)',
  '  Copyright (c) 2014-2016, SourceLair Private Company (https://www.sourcelair.com)',
  '  Copyright (c) 2012-2013, Christopher Jeffrey (https://github.com/chjj/)',
  'Full text: THIRD-PARTY-NOTICES.md.',
];
for (const line of header) if (/[{}]/.test(line)) throw new Error('a brace in the header would open a nested comment: ' + line);

const hex4 = n => '$' + n.toString(16).toUpperCase().padStart(4, '0');
let out = '{ ' + header.join('\n  ') + ' }\n\nconst\n';
out += `  TyTermCharsetCount = ${tables.length};\n`;
out += `  TyTermCharsetKeyCount = ${keys.length};\n`;
out += `  TyTermCharsetKeys: array[0..${keys.length - 1}] of Char = (${keys.map(k => (k === "'" ? "''''" : `'${k}'`)).join(', ')});\n`;
out += `  TyTermCharsetOfKey: array[0..${keys.length - 1}] of Byte = (${ofKey.join(', ')});\n`;
out += `  TyTermCharsetMap: array[1..${tables.length}, $20..$7E] of Word = (\n`;
out += tables.map((t, n) => {
  const row = [];
  for (let c = 0x20; c <= 0x7e; c++) {
    const r = t[String.fromCharCode(c)];
    row.push(hex4(r ? r.charCodeAt(0) : 0));
  }
  const lines = [];
  for (let k = 0; k < row.length; k += 12) lines.push('      ' + row.slice(k, k + 12).join(', '));
  return `    ( { table ${n + 1} }\n${lines.join(',\n')})`;
}).join(',\n');
out += ');\n';
L.writeGenerated('source/tyControls.Terminal.Charsets.inc', out);
console.log(`keys ${keys.join(' ')}; tables ${tables.length}`);
process.exit(0);
